const TL = 0.1; // default outer wall thickness (100 mm hebel)
const TD = 0.075; // default inner partition thickness (75 mm hebel)
const H_LT = 3.6; // floor-to-floor height (m)

function door(
  id: string,
  offset: number,
  width: number,
  label: string,
  swing: 1 | -1 = 1,
  openPct = 35,
): Opening {
  return {
    id,
    kind: "door",
    width,
    height: 2.15,
    sill: 0,
    offset,
    swing,
    openPct,
    frameMaterialId: "wood_teak",
    label,
  };
}

function win(
  id: string,
  offset: number,
  width: number,
  height: number,
  sill: number,
  label: string,
  openPct = 60,
): Opening {
  return {
    id,
    kind: "window",
    width,
    height,
    sill,
    offset,
    swing: 1,
    openPct,
    frameMaterialId: "alu_dark",
    glassMaterialId: "glass_clear",
    label,
  };
}

function vent(
  id: string,
  offset: number,
  width: number,
  sill: number,
  label: string,
): Opening {
  return {
    id,
    kind: "vent",
    width,
    height: 0.22,
    sill,
    offset,
    swing: 1,
    openPct: 100,
    frameMaterialId: "concrete_roster",
    label,
  };
}

function wall(
  id: string,
  name: string,
  x1: number,
  z1: number,
  x2: number,
  z2: number,
  exterior: boolean,
  openings: Opening[] = [],
  options?: { height?: number; partyWallSide?: "left" | "right" | null },
): Wall {
  return {
    id,
    name,
    start: { x: x1, z: z1 },
    end: { x: x2, z: z2 },
    thickness: exterior ? TL : TD,
    height: options?.height ?? H_LT,
    materialId: exterior ? "wall_ext_ivory" : "wall_int_ivory",
    exterior,
    partyWallSide: options?.partyWallSide ?? null,
    openings,
  };
}

