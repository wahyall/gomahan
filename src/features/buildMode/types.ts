export const BUILD_FORMAT_VERSION = 2 as const;

/** Half-meter integer sub-grid; 2 cells = 1.0m major architectural tile. */
export const CELL_SIZE = 0.5;
export const MAJOR_TILE_CELLS = 2;

export type WallVisibilityMode = "up" | "cutaway" | "down";
export type RoofVisibilityMode = "auto" | "show" | "hide";
export type BuildTimeOfDay = "morning" | "noon" | "sunset" | "night";

export type BuildCategoryId =
  | "build"
  | "walls"
  | "floors"
  | "openings"
  | "stairs_roof"
  | "outdoor"
  | "furniture"
  | "lighting";

export type BuildToolId =
  | "select"
  | "wall_straight"
  | "wall_room"
  | "wall_diagonal"
  | "fence"
  | "floor_tile"
  | "floor_rect"
  | "floor_fill"
  | "opening"
  | "stair"
  | "roof"
  | "pool"
  | "terrain"
  | "object"
  | "eyedropper"
  | "sledgehammer";

export interface BuildLotConfig {
  name: string;
  /** Number of 0.5m cells along X (width). 10 cells = 5.0m kavling. */
  cols: number;
  /** Number of 0.5m cells along Z (depth). 34 cells = 17.0m kavling. */
  rows: number;
  cellSize: number;
  /** Foundation plinth height in meters above ground datum (default 0.35m). */
  foundationHeight: number;
  /** Target construction budget in IDR. */
  budgetIdr: number;
  /** Vertex elevation offsets length = (cols + 1) * (rows + 1), relative to datum 0. */
  terrainHeights: number[];
}

export interface BuildLevel {
  index: number; // 0 = Lantai 1, 1 = Lantai 2, 2 = Lantai 3 / Atap
  name: string;
  /** Elevation in meters relative to top of foundation slab. */
  elevation: number;
  /** Clear floor-to-floor height in meters. */
  height: number;
}

export interface BuildWall {
  id: string;
  levelIndex: number;
  /** Grid vertex coordinates (0..cols, 0..rows). */
  x1: number;
  z1: number;
  x2: number;
  z2: number;
  kind: "wall" | "fence" | "halfwall";
  thickness: number;
  height: number;
  paintInnerId: string;
  paintOuterId: string;
}

export type OpeningKind = "door" | "window" | "arch" | "gate";

export interface BuildOpening {
  id: string;
  wallId: string;
  kind: OpeningKind;
  catalogId: string;
  /** Normalized center position along wall [0..1]. */
  tCenter: number;
  width: number;
  height: number;
  sillHeight: number;
  swatchId: string;
  isOpen?: boolean;
}

export interface BuildFloorCell {
  levelIndex: number;
  gx: number;
  gz: number;
  materialId: string;
  isPool?: boolean;
  poolDepth?: number;
}

export interface BuildStair {
  id: string;
  levelIndex: number;
  catalogId: string;
  /** Top-left footprint cell on the active grid. */
  gx: number;
  gz: number;
  widthCells: number;
  lengthCells: number;
  /** 0 = +Z climb, 1 = +X climb, 2 = -Z climb, 3 = -X climb */
  rotationQuarter: 0 | 1 | 2 | 3;
  style: "concrete" | "wood_steel" | "open_riser";
  swatchId: string;
  hasLanding: boolean;
}

export interface BuildRoof {
  id: string;
  levelIndex: number;
  kind: "shed" | "gable" | "hip" | "flat";
  gx1: number;
  gz1: number;
  gx2: number;
  gz2: number;
  pitchDeg: number;
  overhang: number;
  eaveHeight: number;
  materialId: string;
  autoGenerated: boolean;
}

export type ObjectHostType = "floor" | "wall" | "surface" | "ceiling";

export interface BuildObject {
  id: string;
  levelIndex: number;
  catalogId: string;
  /** Lot-local coordinates in meters (0..cols*cellSize, y above level floor, 0..rows*cellSize). */
  x: number;
  y: number;
  z: number;
  rotationY: number;
  swatchId: string;
  hostType: ObjectHostType;
  hostId?: string;
}

export interface BuildDocument {
  formatVersion: typeof BUILD_FORMAT_VERSION;
  id: string;
  updatedAt: string;
  lot: BuildLotConfig;
  levels: BuildLevel[];
  walls: BuildWall[];
  openings: BuildOpening[];
  floorCells: Record<string, BuildFloorCell>;
  stairs: BuildStair[];
  roofs: BuildRoof[];
  objects: BuildObject[];
}

export interface BuildCameraSnapshot {
  target: [number, number, number];
  yaw: number;
  pitch: number;
  distance: number;
}

export interface BuildCostSummary {
  wallsIdr: number;
  openingsIdr: number;
  floorsIdr: number;
  stairsIdr: number;
  roofsIdr: number;
  objectsIdr: number;
  foundationIdr: number;
  totalIdr: number;
  remainingIdr: number;
  overBudget: boolean;
  builtFloorAreaM2: number;
  wallLengthM: number;
}

export type CatalogItemKind =
  | "wall_material"
  | "floor_material"
  | "opening"
  | "stair"
  | "roof_material"
  | "furniture"
  | "light";

export interface CatalogSwatch {
  id: string;
  name: string;
  hex: string;
  roughness?: number;
  metalness?: number;
}

export interface BuildCatalogItem {
  id: string;
  category: BuildCategoryId;
  kind: CatalogItemKind;
  name: string;
  priceIdr: number;
  toolId: BuildToolId;
  /** Footprint dimensions in meters for objects/openings/stairs. */
  sizeM?: [number, number, number];
  /** Tile dimensions in 0.5m cells [cols, rows]. */
  footprintCells?: [number, number];
  hostType?: ObjectHostType;
  /** Walk Mode collision flags: true for sofas/tables, false for rugs/curtains. */
  blocking?: boolean;
  /** Height clearance under/above object; ceiling/wall lights are non-blocking at floor level. */
  walkableSurface?: boolean;
  swatches: CatalogSwatch[];
  description: string;
}

export function floorCellKey(levelIndex: number, gx: number, gz: number): string {
  return `${levelIndex}:${gx}:${gz}`;
}

export function cloneBuildDocument(doc: BuildDocument): BuildDocument {
  return structuredClone(doc);
}
